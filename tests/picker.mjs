// The colour picker in every colour menu (drawn by Edit Mode, dark). Runs on the sample copy (5390).
import { chromium } from 'playwright-core';
const b = await chromium.launch({ channel: 'chrome' });
const results = [];
const check = (name, ok, detail = '') => results.push(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? '  — ' + detail : ''}`);
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const errors = []; p.on('pageerror', e => errors.push(e.message));
await p.addInitScript(() => { try { localStorage.setItem('edit-mode:layers', '0'); } catch {} });
await p.goto('http://localhost:5390'); await p.waitForSelector('.cta-primary');
const html = () => p.$eval('#root', e => e.innerHTML.replace(/ style=""/g, ''));
const start = await html();
await p.keyboard.press('Alt+KeyE'); await p.waitForTimeout(150);
const R = (q) => `edit-mode-root ${q}`;
const bg = () => p.$eval('.cta-primary', e => getComputedStyle(e).backgroundColor);
await p.evaluate(() => window.__editMode.select(document.querySelector('.cta-primary'))); await p.waitForTimeout(80);
await p.locator(R('section:has(h4:text-is("Fill")) .swatch >> visible=true')).first().click(); await p.waitForTimeout(150);
check('the colour menu has our picker, no browser picker', await p.locator(R('.pop .cp-sv')).isVisible() && await p.locator(R('.pop input[type=color]')).count() === 0);
check('it starts at the current colour', (await p.locator(R('.pop .cp input[aria-label="Hex"]')).inputValue()) === 'E2572B', await p.locator(R('.pop .cp input[aria-label="Hex"]')).inputValue());
if (process.env.SHOT) await p.screenshot({ path: process.env.SHOT + '-fill.png', clip: await p.locator(R('.pop')).boundingBox() });
const box = await p.locator(R('.pop .cp-sv')).boundingBox();
await p.mouse.move(box.x + box.width * 0.9, box.y + box.height * 0.1); await p.mouse.down();
await p.mouse.move(box.x + box.width * 0.2, box.y + box.height * 0.8, { steps: 6 }); await p.mouse.up(); await p.waitForTimeout(80);
const after = await bg();
check('dragging in the square changes the fill live', after !== 'rgb(226, 87, 43)' && /^rgb\(/.test(after), after);
check('the menu stays open while dragging', await p.locator(R('.pop .cp-sv')).isVisible());
const hb = await p.locator(R('.pop .cp-hue')).boundingBox();
await p.mouse.click(hb.x + hb.width * 0.66, hb.y + hb.height / 2); await p.waitForTimeout(80);
const blueish = (await bg()).match(/\d+/g).map(Number);
check('the hue slider', blueish[2] > blueish[0], await bg());
const ab = await p.locator(R('.pop .cp-alpha')).boundingBox();
await p.mouse.click(ab.x + ab.width * 0.5, ab.y + ab.height / 2); await p.waitForTimeout(80);
check('the opacity slider', /rgba\(.*0\.5\)/.test(await bg()), await bg());
const hex = p.locator(R('.pop .cp input[aria-label="Hex"]'));
await hex.fill('00AA55'); await hex.press('Enter'); await p.waitForTimeout(80);
check('typing a hex keeps the opacity', (await bg()) === 'rgba(0, 170, 85, 0.5)', await bg());
const op = p.locator(R('.pop .cp input[aria-label="Opacity"]'));
await op.fill('100'); await op.press('Enter'); await p.waitForTimeout(80);
check('opacity 100', (await bg()) === 'rgb(0, 170, 85)', await bg());
await p.keyboard.press('Escape'); await p.waitForTimeout(60);
const steps = []; for (let i = 0; i < 8 && (await html()) !== start; i++) { await p.keyboard.press('Meta+z'); await p.waitForTimeout(60); steps.push(await bg()); }
check('⌘Z back to the start, one step per drag/click/field', (await html()) === start && steps.length <= 5, steps.join(' | '));
// The canvas background: the same picker, no opacity.
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await p.waitForTimeout(80);
await p.locator(R('section.canvas-bg .swatch')).click(); await p.waitForTimeout(150);
check('canvas background: the picker, without opacity', await p.locator(R('.pop .cp-sv')).isVisible() && await p.locator(R('.pop .cp-alpha')).count() === 0);
if (process.env.SHOT) await p.screenshot({ path: process.env.SHOT + '-canvas.png', clip: await p.locator(R('.pop')).boundingBox() });
const sb = await p.locator(R('.pop .cp-sv')).boundingBox();
await p.mouse.click(sb.x + 5, sb.y + sb.height - 5); await p.waitForTimeout(80);
const cbg = await p.evaluate(() => getComputedStyle(document.documentElement).backgroundColor);
check('…dragging paints the canvas', /^rgb\((\d), (\d), (\d)\)$/.test(cbg) || /rgb\(\d{1,2}, \d{1,2}, \d{1,2}\)/.test(cbg), cbg);
await p.keyboard.press('Escape');
await p.locator(R('button[aria-label="Reset canvas background"]')).click();
check('no page errors', !errors.length, errors.join(' | '));
console.log(results.join('\n'));
console.log(`${results.filter(r => r.startsWith('PASS')).length}/${results.length} passed`);
await b.close();
