// The canvas background colour (nothing selected → Canvas section). Runs on the sample copy (5390).
import { chromium } from 'playwright-core';
const b = await chromium.launch({ channel: 'chrome' });
const results = [];
const check = (name, ok, detail = '') => results.push(`${ok ? 'PASS' : 'FAIL'}  ${name}${detail ? '  — ' + detail : ''}`);
const p = await b.newPage({ viewport: { width: 1280, height: 1000 } });
const errors = []; p.on('pageerror', e => errors.push(e.message));
await p.addInitScript(() => { try { localStorage.setItem('edit-mode:layers', '0'); } catch {} });
await p.goto('http://localhost:5390'); await p.waitForSelector('.cta-primary');
const start = await p.$eval('#root', e => e.innerHTML);
const R = (q) => `edit-mode-root ${q}`;
const bg = () => p.evaluate(() => getComputedStyle(document.documentElement).backgroundColor);
const sec = () => p.evaluate(() => { const s = document.querySelector('edit-mode-root').shadowRoot.querySelector('section.canvas-bg'); return !!s && !s.hidden && !s.closest('[hidden]'); });
check('Edit Mode off: no panel', !(await sec()));
await p.keyboard.press('Alt+KeyE'); await p.waitForTimeout(200);
check('on, nothing selected: the Canvas section shows', await sec());
const hex = p.locator(R('input[aria-label="Canvas background"]'));
check('it reads the default grey', (await hex.inputValue()).toUpperCase() === 'E9E9EB', await hex.inputValue());
await hex.fill('1E1E1E'); await hex.press('Enter'); await p.waitForTimeout(80);
check('typing a colour paints the canvas', (await bg()) === 'rgb(30, 30, 30)', await bg());
check('the Duplicate page icon turns light on a dark canvas', (await p.evaluate(() => getComputedStyle(document.querySelector('edit-mode-root').shadowRoot.querySelector('.dup-page')).color)) === 'rgba(255, 255, 255, 0.6)');
check('…not a change to the app (nothing to push)', await p.evaluate(() => window.__editMode.changes.count) === 0);
check("…the page's own background is untouched", (await p.$eval('body', e => getComputedStyle(e).backgroundColor)) !== 'rgb(30, 30, 30)');
await p.evaluate(() => window.__editMode.select(document.querySelector('.hero'))); await p.waitForTimeout(80);
check('selecting something: the Canvas section gives way', !(await sec()));
await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await p.keyboard.press('Escape'); await p.waitForTimeout(80);
check('nothing selected again: back', await sec());
await p.reload(); await p.waitForSelector('.cta-primary'); await p.waitForTimeout(300);
check('remembered after a reload', (await bg()) === 'rgb(30, 30, 30)', await bg());
await p.locator(R('button[aria-label="Reset canvas background"]')).click(); await p.waitForTimeout(80);
check('reset: back to the grey', (await bg()) === 'rgb(233, 233, 235)', await bg());
await p.locator(R('section.canvas-bg .swatch')).click(); await p.waitForTimeout(120);
check('the swatch opens the colour menu', await p.locator(R('.pop')).isVisible());
await p.keyboard.press('Escape');
await p.keyboard.press('Alt+KeyE'); await p.waitForTimeout(200);
check('off: the page is as it was, no panel', (await p.$eval('#root', e => e.innerHTML)) === start && !(await sec()));
check('no page errors', !errors.length, errors.join(' | '));
console.log(results.join('\n'));
console.log(`${results.filter(r => r.startsWith('PASS')).length}/${results.length} passed`);
await b.close();
